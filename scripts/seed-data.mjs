const CH1 = `The second of December put Ione Faber ashore at Vess on the last crossing before the closure, with two crates, a sealed envelope from the Board, and four hours of daylight.

She counted the steps up from the harbour because counting was what she did with silence. Two hundred and six to the tram road, then the long grey walk out along the spine of the island, the grass lying flat under a wind that had been blowing, Teodor Vance had told her on the crossing, since October and would not stop until March.

The Salt Lantern stood at the end of it. Two hundred years of whitewash had gone soft on the seaward side, and the door had been painted so many times it no longer fit its own frame. She had to lean on it.

Inside, the cold was different — older, held in the stone. She lit the range, put the crates down, and did not unpack them. She went up.

The lamp room smelled of hot brass and paraffin, which meant someone had been keeping it. The Board's letter had said the station was unmanned since August. The Board's letter had said a number of things.

She checked the clockwork, the reservoir, the wick. All of it was in order in the particular way that meant a careful person had left it, not a hurried one. Then she found the log.

It was where it should have been, on the shelf under the barometer, a black ledger with the year stamped on the spine. Halvard Renn had kept it in a small upright hand that never varied, one line per entry, the way the Board had wanted logs kept forty years ago and had stopped caring about since.

She turned to the last page with writing on it and read backwards, because the end of a log tells you what the beginning cannot.

*14 November. Lit 15:52. Wind NNE 6. Visibility 4 miles falling. Nothing to report.*

Below it:

*15 November. Lit 15:50. Wind NNE 7. Visibility 2 miles. Nothing to report.*

She read on down. And then she stopped, and put her finger on the page, and went back up.

*14 November. Lit 15:52. Wind NNE 6. Visibility 4 miles falling. Nothing to report.*

There were two of them.

Not a correction. Not a struck line. Two complete entries for the fourteenth of November, one after the other, with the fifteenth following as though nothing had happened. The second was dated the same, timed the same, and reported the same weather — and it was not in the same hand.

It was close. Someone had been trying, and whoever it was had been taught by him — the figures were his figures, down to the crossed sevens. But in thirty-one years Halvard Renn had closed *Nothing to report* with a full stop, without exception, and this hand had left it open.

Ione took out her own notebook and copied both entries in pencil. She never logged in ink. Ink could be gone over.

Then she opened the ledger at the next clean line and began her own record of the station, seventeen days after the last thing anyone had written in it.

*2 December. Took charge of the light. Lamp room found in service. See separate note.*

Outside, the light came on above her at 15:51, because she had set the clockwork herself an hour ago, and the beam went out over the water and found nothing, the way it had every evening for two hundred years.

She stood in the lamp room until it was fully dark, holding a ledger written by a man who had been dead since August, reading a day that had happened twice.`;

